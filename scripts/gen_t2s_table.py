# Regenerates crates/fleet-snowfluff-ai/src/memory/t2s_table.rs from OpenCC's TSCharacters.txt
# (Apache-2.0, https://github.com/BYVoid/OpenCC). Run: python3 scripts/gen_t2s_table.py
# Only one-to-one character mappings are kept: matching needs a character map, not phrase conversion.
import os,urllib.request
HERE=os.path.dirname(os.path.abspath(__file__))
OUT=os.path.join(HERE,"..","crates","fleet-snowfluff-ai","src","memory","t2s_table.rs")
CACHE=os.path.join(os.environ.get("TMPDIR","/tmp"),"opencc-TSCharacters.txt")
if not os.path.exists(CACHE):
    urllib.request.urlretrieve("https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/TSCharacters.txt",CACHE)
pairs={}
for line in open(CACHE,encoding="utf8"):
    if line.startswith("#") or "\t" not in line: continue
    key,values=line.rstrip("\n").split("\t")
    value=values.split()[0]
    if len(key)==1 and len(value)==1 and key!=value:
        pairs[key]=value
rows=sorted(pairs.items(),key=lambda kv: ord(kv[0]))
with open(OUT,"w",encoding="utf8") as f:
    f.write("// Generated by scripts/gen_t2s_table.py from OpenCC's TSCharacters.txt (Apache-2.0,\n")
    f.write("// https://github.com/BYVoid/OpenCC). Do not edit by hand.\n\n")
    f.write("/// Traditional character to Simplified character, sorted by the Traditional one.\n")
    f.write("pub(super) static TRADITIONAL_TO_SIMPLIFIED: &[(char, char)] = &[\n")
    for k,v in rows:
        f.write(f"    ('{k}', '{v}'),\n")
    f.write("];\n")
print(f"wrote {len(rows)} mappings")
